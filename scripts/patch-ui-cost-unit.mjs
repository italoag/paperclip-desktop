#!/usr/bin/env node
/**
 * Relabels Paperclip's cost figures from dollars to ACUs.
 *
 * # Why this is needed
 *
 * Paperclip's ledger stores a single integer of cents, and the `devin_local`
 * adapter reports ACUs into it one-for-one (see `acu.ts`). The number is then
 * correct but the unit is not: 0.32 ACU renders as "$0.32", and the monthly
 * budget input asks for dollars when it is really capping ACUs.
 *
 * There is no server-side or adapter-side fix. `costUsd` is the only numeric
 * channel into the ledger and the label lives in the prebuilt UI, so the unit
 * has to be corrected where it is rendered.
 *
 * # What it changes
 *
 * Two spots, both unique in the bundle:
 *
 * 1. The cents formatter — one function, used in 59 places, that turns
 *    `32` into `"$0.32"`.
 * 2. The `$` prefix on the monthly budget input.
 *
 * # The honest caveat
 *
 * The formatter takes a number and nothing else, so it cannot know which
 * adapter produced a given figure. Relabelling it is therefore global: if this
 * install ever runs an adapter that reports real dollars — Claude, Codex — that
 * adapter's costs will also read "ACU" and be wrong. This patch suits an
 * install where Devin is the only adapter in use, which is what it is built for.
 *
 * # On upgrades
 *
 * This edits a minified bundle whose identifiers are generated by the minifier
 * and change on every release, so the patterns match on code *shape* rather
 * than on names, and a miss is a hard error. A silently unpatched bundle would
 * put dollar signs back on ACU figures without anyone noticing.
 */

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

export const UNIT_LABEL = "ACU";

/**
 * `function X(e){return`$${(e/100).toLocaleString("en-US",{...})}`}`
 *
 * The backreference ties the parameter to its use, so this cannot match some
 * other two-decimal formatter that happens to look similar.
 */
const CENTS_FORMATTER =
  /function ([A-Za-z_$][\w$]*)\((\w)\)\{return`\$\$\{\(\2\/100\)\.toLocaleString\("en-US",\{minimumFractionDigits:2,maximumFractionDigits:2\}\)\}`\}/;

/** The `$` adornment in front of the monthly budget input. */
const BUDGET_PREFIX = /children:"\$"\}\)/;

export function patchCostUnit(source, unit = UNIT_LABEL) {
  const formatterMatches = source.match(new RegExp(CENTS_FORMATTER, "g")) ?? [];
  const prefixMatches = source.match(new RegExp(BUDGET_PREFIX, "g")) ?? [];

  let patched = source;

  if (formatterMatches.length === 1) {
    patched = patched.replace(
      CENTS_FORMATTER,
      (_match, fn, arg) =>
        `function ${fn}(${arg}){return\`\${(${arg}/100).toLocaleString("en-US",` +
        `{minimumFractionDigits:2,maximumFractionDigits:2})} ${unit}\`}`,
    );
  }

  if (prefixMatches.length === 1) {
    patched = patched.replace(BUDGET_PREFIX, `children:"${unit}"})`);
  }

  return {
    source: patched,
    formatter: formatterMatches.length,
    prefix: prefixMatches.length,
  };
}

/** The one bundle that carries the app shell; the rest are lazy chunks. */
function mainBundle(assetsDir) {
  const candidates = readdirSync(assetsDir)
    .filter((name) => /^index-.*\.js$/.test(name))
    .map((name) => path.join(assetsDir, name));

  if (candidates.length === 0) {
    throw new Error(`[patch-ui-cost-unit] no index-*.js found in ${assetsDir}`);
  }
  return candidates.sort(
    (a, b) => readFileSync(b).length - readFileSync(a).length,
  )[0];
}

/**
 * Renames the patched bundle and repoints everything that loads it.
 *
 * Vite derives the filename hash from the *upstream* content, so patching in
 * place leaves the URL unchanged — and the server serves assets with
 * `Cache-Control: public, max-age=31536000, immutable`. An installed webview
 * therefore keeps its pre-patch copy for a year and never asks again: the fix
 * ships, the server serves it, and the window still shows the old bytes.
 *
 * Changing the URL is what makes `immutable` work in our favour instead of
 * against us. The name is rewritten in `index.html` and in every lazy chunk
 * that imports the shared bundle.
 */
function renameForCacheBusting(assetsDir, uiDistDir, file, source) {
  const digest = createHash("sha256").update(source).digest("hex").slice(0, 8);
  const oldName = path.basename(file);
  const newName = oldName.replace(/\.js$/, `-${digest}.js`);
  if (oldName === newName) return { oldName, newName, rewritten: 0 };

  writeFileSync(path.join(assetsDir, newName), source);
  rmSync(file);

  let rewritten = 0;
  const targets = [
    path.join(uiDistDir, "index.html"),
    ...readdirSync(assetsDir)
      .filter((name) => name.endsWith(".js"))
      .map((name) => path.join(assetsDir, name)),
  ];

  for (const target of targets) {
    if (!existsSync(target)) continue;
    const contents = readFileSync(target, "utf8");
    if (!contents.includes(oldName)) continue;
    writeFileSync(target, contents.split(oldName).join(newName));
    rewritten += 1;
  }

  return { oldName, newName, rewritten };
}

export function patchUiDist(uiDistDir, unit = UNIT_LABEL) {
  const assetsDir = path.join(uiDistDir, "assets");
  const file = mainBundle(assetsDir);
  const source = readFileSync(file, "utf8");

  // Already patched: the formatter no longer matches but the unit is present.
  if (!CENTS_FORMATTER.test(source) && source.includes(`)} ${unit}\``)) {
    return { file, formatter: 0, prefix: 0, alreadyPatched: true };
  }

  const result = patchCostUnit(source, unit);

  if (result.formatter !== 1) {
    throw new Error(
      `[patch-ui-cost-unit] expected exactly one cents formatter in ${path.basename(file)}, found ${result.formatter}.\n` +
        "The Paperclip UI changed how it renders costs. Re-derive the pattern before " +
        "shipping, or ACU figures will be labelled as dollars again.",
    );
  }
  if (result.prefix !== 1) {
    throw new Error(
      `[patch-ui-cost-unit] expected exactly one budget "$" prefix in ${path.basename(file)}, found ${result.prefix}.\n` +
        "The monthly budget input changed shape; re-derive the pattern.",
    );
  }

  const renamed = renameForCacheBusting(assetsDir, uiDistDir, file, result.source);
  return { file, ...result, ...renamed, alreadyPatched: false };
}

function main() {
  const [uiDistDir, unit] = process.argv.slice(2);
  if (!uiDistDir) {
    console.error("usage: patch-ui-cost-unit.mjs <ui-dist-dir> [unit]");
    process.exit(1);
  }
  const { file, alreadyPatched, newName, rewritten } = patchUiDist(
    uiDistDir,
    unit || UNIT_LABEL,
  );
  console.log(
    alreadyPatched
      ? `[patch-ui-cost-unit] already labelled ${path.basename(file)}`
      : `[patch-ui-cost-unit] relabelled in ${unit || UNIT_LABEL}, renamed to ` +
          `${newName} (${rewritten} references rewritten)`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) main();
